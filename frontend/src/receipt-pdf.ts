import { jsPDF } from "jspdf";
import type { PublicOrderDetails, PublicVerificationResult } from "./services/api";

function addLine(
  pdf: jsPDF,
  text: string,
  y: number,
  options: { size?: number; bold?: boolean; mono?: boolean; color?: [number, number, number] } = {},
): number {
  const { size = 10, bold = false, mono = false, color = [29, 51, 37] } = options;
  pdf.setFont(mono ? "courier" : "helvetica", bold ? "bold" : "normal");
  pdf.setFontSize(size);
  pdf.setTextColor(...color);
  const lines = pdf.splitTextToSize(text, 174);
  if (y + lines.length * (size * 0.48) > 280) {
    pdf.addPage();
    y = 18;
  }
  pdf.text(lines, 18, y);
  return y + lines.length * (size * 0.48) + 2;
}

function readableDate(value: string | undefined): string {
  if (!value) return "Not available";
  const date = new Date(value);
  return Number.isNaN(date.getTime())
    ? "Not available"
    : new Intl.DateTimeFormat("en", { dateStyle: "medium", timeStyle: "short" }).format(date);
}

export function createVerificationReceiptPdf(
  order: PublicOrderDetails,
  result: PublicVerificationResult,
): jsPDF {
  const pdf = new jsPDF({ unit: "mm", format: "a4" });
  let y = 20;
  y = addLine(pdf, "VERDANT · RETAILTRACE", y, { size: 10, bold: true, color: [91, 117, 78] });
  y = addLine(pdf, "Blockchain verification receipt", y, { size: 22, bold: true });
  y = addLine(pdf, result.status === "VERIFIED" ? "Blockchain record verified" : `Verification status: ${result.status}`, y + 3, {
    size: 14,
    bold: true,
    color: result.status === "VERIFIED" ? [69, 112, 55] : [128, 83, 50],
  });
  y = addLine(pdf, result.explanation, y + 1);
  y = addLine(pdf, "PURCHASE", y + 6, { size: 9, bold: true, color: [91, 117, 78] });
  y = addLine(pdf, `Order reference: ${order.orderReference ?? "Not available"} (Verdant's identifier for this purchase)`, y, { bold: true });
  y = addLine(pdf, `Order date: ${readableDate(order.orderDate)}`, y);
  for (const product of order.products ?? []) {
    y = addLine(pdf, `${product.name} × ${product.quantity}`, y);
  }
  y = addLine(pdf, `Order total: ${order.total ?? "Not available"}`, y, { bold: true });
  y = addLine(pdf, "VERIFICATION DETAILS", y + 6, { size: 9, bold: true, color: [91, 117, 78] });
  y = addLine(pdf, `RetailTrace record ID: ${result.recordId ?? order.retailTraceRecordId ?? "Not available"}`, y, { mono: true });
  y = addLine(pdf, `Blockchain transaction ID: ${result.transactionId ?? order.transactionId ?? "Not available"}`, y, { mono: true });
  y = addLine(pdf, `Network: ${result.network ?? "Not available"}`, y);
  y = addLine(pdf, `Block height: ${result.blockHeight ?? "Not available"}`, y);
  y = addLine(pdf, `Publication timestamp: ${readableDate(result.publicationTimestamp)}`, y);
  y = addLine(pdf, `Publication status: ${result.publicationStatus ?? "Not available"}`, y);
  y = addLine(pdf, `Transaction exists: ${result.checks.transactionExists === null ? "Unable to check" : result.checks.transactionExists ? "Yes" : "No"}`, y);
  y = addLine(pdf, `RetailTrace record found: ${result.checks.recordFound === null ? "Unable to check" : result.checks.recordFound ? "Yes" : "No"}`, y);
  y = addLine(pdf, `Data integrity: ${result.checks.commitmentMatches === null ? "Unable to check" : result.checks.commitmentMatches ? "Commitment matches" : "Commitment does not match"}`, y);
  y = addLine(pdf, `Verification timestamp: ${readableDate(result.verificationTimestamp)}`, y);
  if (result.commitmentHash) {
    y = addLine(pdf, `Cryptographic commitment: ${result.commitmentHash}`, y, { mono: true });
  }
  y = addLine(pdf, "ABOUT THIS RESULT", y + 6, { size: 9, bold: true, color: [91, 117, 78] });
  y = addLine(pdf, "Blockchain verification checks that a published cryptographic commitment matches the record checked by RetailTrace. It does not prove that the original information was truthful or that a physical product is genuine.", y);
  addLine(pdf, "Public verification receipt generated by Verdant. Customer contact, address, and payment details are not included.", y + 2, { size: 8, color: [100, 112, 103] });
  return pdf;
}
